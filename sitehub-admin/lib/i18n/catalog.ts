export function translateMessage(locale: string, key: string): string {
  const table = I18N_MESSAGES[locale] ?? en;
  return table[key] ?? en[key] ?? key;
}

export function resolveAppLocale(stored: AppLocale, browserLang?: string): AppLanguageCode {
  if (stored !== "system" && APP_LANGUAGE_CODES.has(stored)) return stored;
  const code = (browserLang || "en").slice(0, 2).toLowerCase();
  if (APP_LANGUAGE_CODES.has(code)) return code as AppLanguageCode;
  return "en";
}
